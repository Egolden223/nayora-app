const displayNamesCache = new Map<Lang, Intl.DisplayNames>();

function regionDisplayNames(lang: Lang): Intl.DisplayNames | null {
  if (typeof Intl === "undefined" || !("DisplayNames" in Intl)) return null;
  let names = displayNamesCache.get(lang);
  if (!names) {
    names = new Intl.DisplayNames([DISPLAY_LOCALE[lang]], { type: "region" });
    displayNamesCache.set(lang, names);
  }
  return names;
}

